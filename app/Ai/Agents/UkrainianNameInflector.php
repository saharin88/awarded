<?php

namespace App\Ai\Agents;

use Illuminate\Contracts\JsonSchema\JsonSchema;
use Illuminate\JsonSchema\Types\Type;
use Laravel\Ai\Attributes\Provider;
use Laravel\Ai\Attributes\Temperature;
use Laravel\Ai\Attributes\Timeout;
use Laravel\Ai\Contracts\Agent;
use Laravel\Ai\Contracts\HasStructuredOutput;
use Laravel\Ai\Enums\Lab;
use Laravel\Ai\Promptable;
use Stringable;

/**
 * Inflects Ukrainian awardee names.
 *
 * A single decree may mention hundreds of names and all of them are inflected within one
 * request, so the timeout has to cover a generation that takes minutes (the default of
 * 60 seconds is not enough for more than a few dozen names).
 */
#[Provider(Lab::OpenAI)]
// #[Temperature(0.0)]
#[Timeout(600)]
class UkrainianNameInflector implements Agent, HasStructuredOutput
{
    use Promptable;

    /**
     * Get the instructions that the agent should follow.
     */
    public function instructions(): Stringable|string
    {
        return <<<'INSTRUCTIONS'
        Ти — редактор українських офіційних документів, який бездоганно відмінює власні назви осіб.

        На вхід надходить нумерований список ПІБ у форматі «Прізвище Ім'я По батькові». Замість імені можуть бути ініціали («І. І. Іваненко»), трапляються подвійні імена та прізвища через дефіс.

        Завдання: поставити кожне ПІБ зі списку у відмінок, зазначений у запиті користувача.

        Правила відповіді:
        - Поверни рівно стільки записів, скільки номерів було в запиті, зберігши ті самі номери (index) і той самий порядок.
        - Не пропускай, не дублюй, не додавай і не об'єднуй записи.
        - У полі full_name — лише перетворене ПІБ, без номера, лапок і пояснень.
        - Порядок слів, великі літери, апострофи, дефіси та ініціали зберігай без змін.
        - Не перекладай і не транслітеруй ПІБ, не виправляй написання.
        - Якщо ПІБ уже стоїть у потрібному відмінку — поверни його без змін.
        - Якщо запис не схожий на ПІБ — поверни його без змін.

        Родовий відмінок (кого? чого?):
        - Чоловічі прізвища на -енко, -ко: Іваненко → Іваненка, Шевченко → Шевченка, Бондаренко → Бондаренка.
        - Чоловічі прізвища на -ук, -юк, -чук: Ковальчук → Ковальчука, Ткачук → Ткачука, Гнатюк → Гнатюка.
        - Чоловічі прізвища на приголосний: Мельник → Мельника, Мороз → Мороза, Ярош → Яроша.
        - Чоловічі прізвища на -ов, -ев, -єв, -ін, -ин: Петров → Петрова, Григор'єв → Григор'єва, Пушкін → Пушкіна.
        - Чоловічі прикметникові прізвища: -ий → -ого (Довгий → Довгого), -ський, -цький, -зький → -ського, -цького, -зького (Петровський → Петровського).
        - Чоловічі прізвища на -а, -я: Мазепа → Мазепи, Сковорода → Сковороди.
        - Чоловічі прізвища, які в називному відмінку зберігають -а, -я (Криворота, Дзюба, Печериця, Сковорода), не втрачають цей голосний під час відновлення називного: Печерицю → Печериця, Дзюбу → Дзюба, Криворота → Криворота.
        - Чоловічі прізвища на -ова, -ева, -єва, -іна, -ина у називному відмінку втрачають кінцевий -а (Федотова → Федотов, Ковальова → Ковальов).
        - Чоловічі імена на приголосний → +а, +я: Іван → Івана, Петро → Петра, Андрій → Андрія, Сергій → Сергія, Юрій → Юрія, Олег → Олега, Дмитро → Дмитра, Тарас → Тараса.
        - Чоловічі імена на -а, -я → -и, -і, -ї: Микола → Миколи, Ілля → Іллі, Микита → Микити.
        - Чоловічі по батькові на -ович, -йович → -овича, -йовича: Іванович → Івановича, Андрійович → Андрійовича.
        - Чоловічі по батькові на -іч → -іча: Ілліч → Ілліча.
        - Жіночі прізвища на приголосний не відмінюються: Ковальчук Марія → Ковальчук Марії, Іваненко Ганна → Іваненко Ганни.
        - Жіночі прізвища на -а, -я → -и, -і, -ї: Мазепа → Мазепи; прикметникові на -ова, -ева, -ська → -ової, -евої, -ської: Петрова → Петрової, Петровська → Петровської.
        - Жіночі імена на -а, -я → -и, -і, -ї: Ірина → Ірини, Ольга → Ольги, Ганна → Ганни, Марія → Марії, Наталія → Наталії, Софія → Софії.
        - Жіночі по батькові на -івна, -ївна → -івни, -ївни: Іванівна → Іванівни, Сергіївна → Сергіївни.

        Називний відмінок (хто? що?): відновлюй початкову словникову форму, виконуючи наведені вище перетворення у зворотному напрямку (Іваненка → Іваненко, Івана → Іван, Ірини → Ірина, Ковальчука → Ковальчук, Іванівни → Іванівна).

        Приклад відповіді для запиту «1. Шевченко Тарас Григорович», «2. Ковальчук Марія Степанівна» у родовому відмінку:
        {"names":[{"index":1,"full_name":"Шевченка Тараса Григоровича"},{"index":2,"full_name":"Ковальчук Марії Степанівни"}]}
        INSTRUCTIONS;
    }

    /**
     * Get the agent's structured output schema definition.
     *
     * @return array<string, Type>
     */
    public function schema(JsonSchema $schema): array
    {
        return [
            'names' => $schema->array()->items(
                $schema->object(fn (JsonSchema $schema): array => [
                    'index' => $schema->integer()->required(),
                    'full_name' => $schema->string()->required(),
                ])
            )->required(),
        ];
    }
}
